    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        int baris = tblMahasiswa.getSelectedRow();
        if (baris == -1) {
        JOptionPane.showMessageDialog(this, "Pilih data di tabel terlebih dahulu!");
        return;
        }
        int pilih = JOptionPane.showConfirmDialog(this,
        "Hapus data " + data[baris][1] + "?", "Konfirmasi",
        JOptionPane.YES_NO_OPTION);
        if (pilih != JOptionPane.YES_OPTION) return;
        for (int i = baris; i < jumlah - 1; i++) { // geser elemen ke kiri
        data[i] = data[i + 1];
        }
        data[jumlah - 1] = new String[5];
        jumlah--;
        tampilkanData();
        bersihkanForm();
    }//GEN-LAST:event_btnHapusActionPerformed

