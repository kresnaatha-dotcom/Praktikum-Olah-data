private void tampilkanData() {
    model.setRowCount(0);
    String sql = "SELECT nim, nama, jk, prodi, ipk FROM mahasiswa ORDER BY nim";
    try (Connection conn = Koneksi.getConnection();
    Statement st = conn.createStatement();
    ResultSet rs = st.executeQuery(sql)) {
    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getString("nim"),
            rs.getString("nama"),
            rs.getString("jk"), 
            rs.getString("prodi"), 
            rs.getString("ipk")
        });
    }
    } catch (SQLException e) {
    JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
    }
}


private String getJenisKelamin() {
    return rbLaki.isSelected() ? "Laki-laki" : "Perempuan";
}

private boolean inputValid() {
    // Validasi NIM dan Nama
    if (txtNim.getText().trim().isEmpty()
            || txtNama.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "NIM dan Nama wajib diisi!");

        return false;
    }

    // Validasi IPK kosong
    if (txtIPK.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "IPK wajib diisi!");

        return false;
    }

    // Validasi IPK harus berupa angka desimal
    try {

        double ipk = Double.parseDouble(txtIPK.getText().trim());

        // Validasi rentang IPK
        if (ipk < 0 || ipk > 4) {

            JOptionPane.showMessageDialog(this,
                    "IPK harus berada antara 0 sampai 4!");

            return false;
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "IPK harus berupa angka!");

        return false;
    }

    return true;
}

