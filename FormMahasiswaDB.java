    private void btnCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariActionPerformed
         // Mengambil kata kunci pencarian
            String kataKunci = txtCari.getText().trim();

            // Jika pencarian kosong, tampilkan seluruh data
            if (kataKunci.isEmpty()) {
                tampilkanData();
                return;
            }

            // Mengosongkan tabel sebelum menampilkan hasil pencarian
            model.setRowCount(0);

            // Perintah SQL untuk mencari nama mahasiswa
            String sql = "SELECT nim, nama, jk, prodi, ipk FROM mahasiswa "
                + "WHERE nama LIKE ?";

            try (Connection conn = Koneksi.getConnection();
                 PreparedStatement ps = conn.prepareStatement(sql)) {

                // Mengisi parameter pencarian
                ps.setString(1, "%" + kataKunci + "%");

                // Menjalankan query
                ResultSet rs = ps.executeQuery();

                // Menghitung hasil pencarian
                int ditemukan = 0;

                // Membaca hasil query satu per satu
                while (rs.next()) {

                    model.addRow(new Object[]{
                        rs.getString("nim"),
                        rs.getString("nama"),
                        rs.getString("jk"),
                        rs.getString("prodi"),
                        rs.getString("ipk")
                    });

                    ditemukan++;
                }

                // Jika data tidak ditemukan
                if (ditemukan == 0) {
                    JOptionPane.showMessageDialog(this,
                            "Data mahasiswa tidak ditemukan!");
                }

            } catch (SQLException e) {

                JOptionPane.showMessageDialog(this,
                        "Gagal mencari data: " + e.getMessage());
            }
    }//GEN-LAST:event_btnCariActionPerformed

